import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('./offer-core.cjs', import.meta.url), 'utf8');
const esm = '// Generated by shared/sync-offer-core.mjs; edit offer-core.cjs.\n' + source.replace(/^'use strict';\n/, '').replace(/^exports\.(\w+) = \1;$/gm, 'export { $1 };');
const target = new URL('./offer-core.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== esm) throw new Error('Run node shared/sync-offer-core.mjs to refresh the ESM core.');
} else await writeFile(target, esm);
